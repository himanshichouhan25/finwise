"""Pydantic V2 schemas for Market Intelligence data, quotes, fundamentals, news, and watchlist."""

from datetime import datetime
from decimal import Decimal
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class MarketDataAttribution(BaseModel):
    """Mandatory data provenance, freshness, and limitation disclosure."""

    provider: str = Field(description="Name of provider, e.g. tapetide, bharatstock, alphavantage, or demo_fallback")
    timestamp: datetime = Field(description="Time of observation or retrieval")
    data_mode: Literal["real_time", "delayed", "end_of_day", "demo"] = Field(
        description="Freshness level of the returned data"
    )
    is_cached: bool = Field(default=False, description="Whether the payload was served from local in-memory cache")
    limitations: list[str] = Field(
        default_factory=list,
        description="Explicit limitations disclosed by provider or free-tier quotas",
    )


class IndexItem(BaseModel):
    """Major benchmark market index quote (e.g. NIFTY 50, SENSEX, BANK NIFTY)."""

    symbol: str
    name: str
    current_price: Decimal
    change_amount: Decimal
    change_pct: Decimal
    open_price: Decimal | None = None
    high_price: Decimal | None = None
    low_price: Decimal | None = None
    previous_close: Decimal | None = None


class MarketStatus(BaseModel):
    """Indian Market trading session operational status."""

    is_open: bool
    exchange: str = "NSE/BSE"
    trading_session: str  # e.g. "Regular Trading", "Pre-Market", "Market Closed"
    timezone: str = "Asia/Kolkata"
    message: str


class MarketOverviewResponse(BaseModel):
    """Aggregated market overview with major benchmark indices and market status."""

    indices: list[IndexItem]
    status: MarketStatus
    attribution: MarketDataAttribution


class StockSearchResult(BaseModel):
    """Stock / Index / ETF search match result."""

    symbol: str
    name: str
    exchange: str = "NSE"
    instrument_type: str = "Stock"


class StockQuoteResponse(BaseModel):
    """Single stock live or EOD quote with day movements."""

    symbol: str
    company_name: str
    exchange: str
    current_price: Decimal
    change_amount: Decimal
    change_pct: Decimal
    open_price: Decimal | None = None
    high_price: Decimal | None = None
    low_price: Decimal | None = None
    previous_close: Decimal | None = None
    volume: int | None = None
    week_52_high: Decimal | None = None
    week_52_low: Decimal | None = None
    attribution: MarketDataAttribution


class OHLCVPoint(BaseModel):
    """Single point in a historical price series."""

    timestamp: str  # YYYY-MM-DD or ISO
    open: Decimal
    high: Decimal
    low: Decimal
    close: Decimal
    volume: int


class StockHistoryResponse(BaseModel):
    """Historical OHLCV price series for charting."""

    symbol: str
    company_name: str
    timeframe: str  # 1M, 6M, 1Y, 5Y
    series: list[OHLCVPoint]
    attribution: MarketDataAttribution


class StockFundamentalsResponse(BaseModel):
    """Key financial metrics and valuation ratios for an equity.

    Missing fields remain None (not 0) to prevent misleading calculations.
    """

    symbol: str
    company_name: str
    sector: str | None = None
    industry: str | None = None
    market_cap_cr: Decimal | None = None  # Market cap in Indian ₹ Crores
    pe_ratio: Decimal | None = None
    pb_ratio: Decimal | None = None
    eps: Decimal | None = None
    debt_to_equity: Decimal | None = None
    roe_pct: Decimal | None = None
    dividend_yield_pct: Decimal | None = None
    revenue_annual_cr: Decimal | None = None
    net_profit_annual_cr: Decimal | None = None
    summary_profile: str | None = None
    attribution: MarketDataAttribution


class StockAiAnalysisRequest(BaseModel):
    """Request payload for AI explanation of stock metrics."""

    symbol: str = Field(min_length=1, max_length=20)


class RatioExplanation(BaseModel):
    """Layman explanation of a financial metric in the context of the stock."""

    metric: str
    value: str
    interpretation: str


class StockAiAnalysisResponse(BaseModel):
    """Plain-English, fact-grounded analysis of stock fundamentals generated by Groq."""

    symbol: str
    company_name: str
    summary_explanation: str
    pros: list[str]
    cons: list[str]
    risks: list[str]
    ratios_explained: list[RatioExplanation]
    model_used: str
    data_timestamp: str
    data_source: str
    sebi_disclaimer: str


class MarketNewsItem(BaseModel):
    """Individual financial news item with AI takeaway."""

    id: str
    title: str
    summary: str
    url: str | None = None
    source: str
    published_at: datetime
    related_symbols: list[str] = Field(default_factory=list)
    ai_takeaway: str | None = None


class MarketNewsResponse(BaseModel):
    """List of market and stock news items with provider attribution."""

    items: list[MarketNewsItem]
    attribution: MarketDataAttribution


class WatchlistItemCreate(BaseModel):
    """Payload to add a stock to personal watchlist."""

    symbol: str = Field(min_length=1, max_length=20)
    company_name: str | None = None
    exchange: str = Field(default="NSE")
    notes: str | None = Field(default=None, max_length=500)


class WatchlistItemResponse(BaseModel):
    """Watchlist entry with optional live quote enrichments."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    user_id: int
    symbol: str
    company_name: str
    exchange: str
    notes: str | None = None
    created_at: datetime
    latest_price: Decimal | None = None
    change_pct: Decimal | None = None
